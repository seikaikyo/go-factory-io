let currentLang = (typeof localStorage !== 'undefined' && localStorage.getItem('studio-lang')) || 'en';

function t(key, ...args) {
  const v = (I18N[currentLang] && I18N[currentLang][key]) || I18N.en[key];
  if (typeof v === 'function') return v(...args);
  return v != null ? v : key;
}

function applyLang(lang) {
  if (!I18N[lang]) return;
  currentLang = lang;
  if (typeof localStorage !== 'undefined') localStorage.setItem('studio-lang', lang);
  document.documentElement.lang = lang === 'zh' ? 'zh-TW' : lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const v = t(key);
    if (typeof v === 'string') el.textContent = v;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  const empty = document.querySelector('#chat-feed .empty-state');
  if (empty) empty.textContent = t('chat.empty');
  const simEmpty = document.querySelector('#sim-feed .empty-state');
  if (simEmpty) simEmpty.textContent = t('sim.feedEmpty');

  const connEl = document.getElementById('conn-status');
  const connText = document.getElementById('conn-text');
  if (connEl && connText) {
    if (connEl.classList.contains('connected')) connText.textContent = t('conn.connected');
    else if (connEl.classList.contains('disconnected')) connText.textContent = t('conn.disconnected');
    else connText.textContent = t('conn.connecting');
  }
}

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => applyLang(btn.dataset.lang));
  });
  applyLang(currentLang);
});
